QA_SYSTEM = """Ты — помощник директора управляющей компании «{company}». Отвечаешь \
на его уточняющие вопросы в Телеграме по ежедневному отчёту. Ниже полный отчёт и \
исходные данные, на которых он построен. Отвечай коротко и по делу, простым языком, \
на «вы». Если в отчёте и сводке ответа нет или нужны подробности по конкретной \
заявке, задаче, адресу или сотруднику — ищи в полных выгрузках инструментом \
search_requests. \
Опирайся только на эти материалы; если ответа нет — честно скажи. Форматирование: \
обычный текст, без markdown-таблиц."""


# Цены Claude Opus 5.5, $ за 1 млн токенов: вход, выход, чтение кэша, запись кэша (1 час).
PRICE = {"input": 4.0, "output": 20.0, "cache_read": 0.20, "cache_write": 8.0}
COSTS = config.ROOT / "data" / "costs.csv"


def log_cost(kind: str, usages: list) -> float:
    """Посчитать стоимость запроса(ов) к Claude и дописать в data/costs.csv."""
    tok = {"input": 0, "output": 0, "cache_read": 0, "cache_write": 0}
    for u in usages:
        tok["input"] += u.input_tokens or 0
        tok["output"] += u.output_tokens or 0
        tok["cache_read"] += getattr(u, "cache_read_input_tokens", 0) or 0
        tok["cache_write"] += getattr(u, "cache_creation_input_tokens", 0) or 0
    usd = sum(tok[k] * PRICE[k] for k in tok) / 1_000_000
    new = not COSTS.exists()
    with COSTS.open("a", encoding="utf-8") as f:
        if new:
            f.write("время;вид;вход;выход;кэш_чтение;кэш_запись;usd\n")
        f.write(f"{datetime.now():%Y-%m-%d %H:%M};{kind};{tok['input']};{tok['output']};"
                f"{tok['cache_read']};{tok['cache_write']};{usd:.4f}\n")
    logging.getLogger("assistent").info("Стоимость (%s): $%.3f, токены %s", kind, usd, tok)
    return usd


def _text(response) -> str:
    if response.stop_reason == "refusal":
        raise RuntimeError("Claude отказался обрабатывать запрос")
    return "".join(b.text for b in response.content if b.type == "text")


def make_report(data: str, now: datetime) -> tuple[str, str]:
    """Возвращает (текст для голоса, полный отчёт в markdown)."""
    # Длинный ответ — получаем потоком, чтобы не упереться в таймаут.
    with client.beta.messages.stream(
        model=config.MODEL,
        max_tokens=64000,
        output_config={"effort": "high"},
        system=REPORT_SYSTEM.format(company=config.COMPANY_NAME,
                                    voice_max=config.VOICE_MAX_CHARS),
        messages=[{
            "role": "user",
            "content": f"Сейчас {now:%d.%m.%Y %H:%M}. Данные:\n\n{data}",
        }],
        **FALLBACK,
    ) as stream:
        response = stream.get_final_message()
    log_cost("отчёт", [response.usage])
    if response.stop_reason == "max_tokens":
        raise RuntimeError("Ответ Claude оборвался: не хватило лимита max_tokens")
    text = _text(response)
    voice = re.search(r"<voice>(.*?)</voice>", text, re.S)
    full = re.search(r"<full>(.*?)</full>", text, re.S)
    if not voice or not full:
        raise RuntimeError("Ответ Claude не в ожидаемом формате:\n" + text[:500])
    return fit_voice(voice.group(1).strip()), full.group(1).strip()


def fit_voice(text: str) -> str:
    """Если голосовая сводка вышла длиннее нормы — просим Claude её ужать."""
    if len(text) <= config.VOICE_MAX_CHARS * 1.1:
        return text
    response = client.beta.messages.create(
        model=config.MODEL,
        max_tokens=4000,
        output_config={"effort": "low"},
        messages=[{"role": "user", "content":
                   f"Сократи эту голосовую сводку для директора до {config.VOICE_MAX_CHARS} "
                   "знаков. Оставь только самые острые проблемы масштаба дома или сотрудника "
                   "(не больше трёх) и фразу с цифрами, сохрани разговорный стиль и концовку. "
                   "Верни только текст сводки.\n\n"
                   + text}],
        **FALLBACK,
    )
    log_cost("сокращение голоса", [response.usage])
    return _text(response).strip()


SPOKEN_ANSWER = """Директор за рулём: вопрос задан голосом, ответ будет озвучен. \
Ответь коротко — две-четыре фразы, не больше {limit} знаков, только суть. Разговорная \
речь, на «вы». Без markdown, списков, эмодзи и сокращений: числа, номера и адреса пиши \
так, как их произносят. Вопрос распознан из речи автоматически — если слово похоже на \
искажённую фамилию, адрес или номер, сопоставь с данными. Если вопрос непонятен, \
коротко переспроси."""


def answer(question: str, report: str, data: str, tables: list[sources.Table],
           history: list[tuple[str, str]] = (), spoken: bool = False) -> str:
    """Ответ на вопрос директора. history — предыдущие пары (вопрос, ответ) за день,
    чтобы понимать уточнения вроде «а по Зуевой?»."""
    @beta_tool
    def search_requests(query: str) -> str:
        """Ищет заявки жителей, задачи директора и входящие письма в полных выгрузках
        из CRM (не только в отчёте). Находит строки, где встречаются все слова запроса.

        Args:
            query: 1–3 слова: номер заявки или задачи, улица и/или номер дома, фамилия
                сотрудника, слово из текста (например «32700», «6356», «Ленина 15», «Иванова»,
                «прокуратура»).
        """
        return sources.search(tables, query)

    messages = []
    for q, a in history:
        messages += [{"role": "user", "content": q}, {"role": "assistant", "content": a}]
    if spoken:
        question += "\n\n" + SPOKEN_ANSWER.format(limit=config.ANSWER_VOICE_MAX_CHARS)
    messages.append({"role": "user", "content": question})

    runner = client.beta.messages.tool_runner(
        model=config.MODEL,
        max_tokens=8000,
        max_iterations=6,
        output_config={"effort": "medium"},
        system=[
            {"type": "text", "text": QA_SYSTEM.format(company=config.COMPANY_NAME)},
            # Отчёт и сводка одинаковы для всех вопросов за день — кэшируем, так дешевле.
            {"type": "text", "text": f"# Отчёт\n\n{report}\n\n# Сводка данных\n\n{data}",
             "cache_control": {"type": "ephemeral", "ttl": "1h"}},
        ],
        tools=[search_requests],
        messages=messages,
        **FALLBACK,
    )
    final, usages = None, []
    for message in runner:  # каждый шаг (поиск по выгрузке и т. п.) — отдельный запрос
        usages.append(message.usage)
        final = message
    log_cost("вопрос", usages)
    return _text(final).strip()
